export type MappedLucideName = keyof typeof HUGEICONS_BY_LUCIDE_NAME;

type HugeiconNode = (typeof HUGEICONS_BY_LUCIDE_NAME)[MappedLucideName];

// per-element stroke styling would beat the svg root, so drop it and let size, strokeWidth,
// color and the redesign's 1.75 stroke rule apply. fill-only shapes keep their fill and skip
// the root stroke so they don't turn into outlines.
const ROOT_OWNED_ATTRS = new Set([
  "stroke",
  "strokeWidth",
  "strokeLinecap",
  "strokeLinejoin",
  "color",
]);

function rootStyledAttrs(attrs: HugeiconNode[number][1]): Record<string, string> {
  const kept: Record<string, string> = {};
  for (const [name, value] of Object.entries(attrs)) {
    if (!ROOT_OWNED_ATTRS.has(name)) kept[name] = String(value);
  }
  if (!("stroke" in attrs) && "fill" in attrs) kept.stroke = "none";
  return kept;
}

export function lucideReactIconNode(name: MappedLucideName): LucideReactIconNode {
  // hugeicons types tags as string; the free set only draws lucide's svg element types
  return HUGEICONS_BY_LUCIDE_NAME[name].map(
    ([tag, attrs]) => [tag, rootStyledAttrs(attrs)] as LucideReactIconNode[number],
  );
}

// vanilla lucide sets attributes verbatim, so keys go kebab-case and React's key is dropped
export function lucideIconNode(name: MappedLucideName): LucideIconNode {
  return HUGEICONS_BY_LUCIDE_NAME[name].map(([tag, attrs]) => {
    const kebabAttrs: Record<string, string> = {};
    for (const [attr, value] of Object.entries(rootStyledAttrs(attrs))) {
      if (attr !== "key") kebabAttrs[attr.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)] = value;
    }
    return [tag, kebabAttrs];
  });
}
