// apps/web/scripts/generate-hugeicons-shims.ts
// writes the lucide alias shims in src/fincke/icons from hugeiconsMap.ts & lucide's alias names
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

import * as LucideReact from "lucide-react/dist/esm/lucide-react.js";
import * as Lucide from "lucide/dist/esm/lucide/src/lucide.js";

import { HUGEICONS_BY_LUCIDE_NAME } from "../src/fincke/icons/hugeiconsMap.ts";

const iconsDir = NodePath.join(import.meta.dirname, "../src/fincke/icons");
const repoRoot = NodePath.join(import.meta.dirname, "../../..");
const names = Object.keys(HUGEICONS_BY_LUCIDE_NAME).toSorted();

// ESM exports are static, so every alias lucide ships for a mapped icon is listed by name;
// a missed alias would fall back to the lucide glyph and break lucideIconByName identity.
function aliasesOf(exports: Record<string, unknown>, canonical: unknown): string[] {
  return Object.keys(exports)
    .filter((key) => exports[key] === canonical)
    .toSorted();
}

function exportLine(name: string, aliases: ReadonlyArray<string>): string {
  if (!aliases.includes(name)) throw new Error(`lucide has no icon named ${name}`);
  const specifiers = aliases.map((alias) => (alias === name ? name : `${name} as ${alias}`));
  return `export { ${specifiers.join(", ")} }`;
}

const reactExports: Record<string, unknown> = LucideReact;
const reactIcons = LucideReact.icons as Record<string, unknown>;
const componentsModule = [
  "// apps/web/src/fincke/icons/hugeiconComponents.ts",
  "// lucide-react components drawn w/ hugeicons free glyphs; generated by scripts/generate-hugeicons-shims.ts",
  'import { createLucideIcon } from "lucide-react/dist/esm/lucide-react.js";',
  'import { lucideReactIconNode, type MappedLucideName } from "./hugeiconsMap";',
  "",
  "function hugeicon(name: MappedLucideName) {",
  '  const kebabName = name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();',
  "  return createLucideIcon(kebabName, lucideReactIconNode(name));",
  "}",
  "",
  ...names.map((name) => `export const ${name} = /* @__PURE__ */ hugeicon("${name}");`),
  "",
].join("\n");

// the shim only re-exports, so bundles resolve each import straight to its source module
// and the full lucide set behind `icons` stays in lucideIconByName's lazy chunk
const reactShim = [
  "// apps/web/src/fincke/icons/lucide-react.ts",
  "// lucide-react w/ hugeicons free overrides; generated by scripts/generate-hugeicons-shims.ts",
  "",
  "// vite aliases only the bare `lucide-react` specifier, so this entry path reaches the real package",
  'export * from "lucide-react/dist/esm/lucide-react.js";',
  'export { icons } from "./lucideReactIcons";',
  ...names.map(
    (name) =>
      `${exportLine(name, aliasesOf(reactExports, reactIcons[name]))} from "./hugeiconComponents";`,
  ),
  "",
].join("\n");

const vanillaExports: Record<string, unknown> = Lucide;
const vanillaShim = [
  "// apps/web/src/fincke/icons/lucide.ts",
  "// vanilla lucide w/ hugeicons free overrides for MorphIcon; generated by scripts/generate-hugeicons-shims.ts",
  'import { lucideIconNode } from "./hugeiconsMap";',
  "",
  "// vite aliases only the bare `lucide` specifier, so this entry path reaches the real package",
  'export * from "lucide/dist/esm/lucide/src/lucide.js";',
  "",
  ...names.map((name) => `const ${name} = /* @__PURE__ */ lucideIconNode("${name}");`),
  "",
  ...names.map((name) => `${exportLine(name, aliasesOf(vanillaExports, vanillaExports[name]))};`),
  "",
].join("\n");

const outputs = {
  "hugeiconComponents.ts": componentsModule,
  "lucide-react.ts": reactShim,
  "lucide.ts": vanillaShim,
};
const paths = Object.entries(outputs).map(([file, source]) => {
  const path = NodePath.join(iconsDir, file);
  NodeFS.writeFileSync(path, source);
  return path;
});
NodeChildProcess.execFileSync(NodePath.join(repoRoot, "node_modules/.bin/vp"), ["fmt", ...paths], {
  cwd: repoRoot,
  stdio: "inherit",
});
